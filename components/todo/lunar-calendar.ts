export function lunarOccurrence(year:number, month:number, day:number) {
  const record=yearData[year-1901];
  if(!record || !Number.isInteger(month) || month<1 || month>12)return "";
  // Skip the extra lunar month. Family anniversaries use the regular month.
  const index=month-1+(record.leapSlot>0 && month>=record.leapSlot ? 1 : 0);
  if(!Number.isInteger(day) || day<1 || day>record.lengths[index])return "";
  const offset=record.lengths.slice(0,index).reduce((sum,days)=>sum+days,day-1);
  return new Date(Date.parse(record.newYear+"T12:00:00Z")+offset*86400000).toISOString().slice(0,10);
}

export function nextLunarOccurrence(start:string,end:string,month:number,day:number) {
  const first=Math.max(1901,Number(start.slice(0,4))-1);
  const last=Math.min(2100,end ? Number(end.slice(0,4)) : 2100);
  for(let year=first;year<=last;year++) {
    const date=lunarOccurrence(year,month,day);
    if(date && date>=start && (!end || date<=end))return date;
  }
  return "";
}
